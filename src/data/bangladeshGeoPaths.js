// ভৌগোলিক স্থানাঙ্ক (lat, lng) কে SVG ক্যানভাস কোঅর্ডিনেট (x, y) এ রূপান্তর
export const projectGeoCoordinates = (lat, lng, width = 600, height = 760) => {
  const minLng = 88.0;
  const maxLng = 92.75;
  const minLat = 20.65;
  const maxLat = 26.65;

  const paddingX = 40;
  const paddingY = 45;

  const usableWidth = width - (paddingX * 2);
  const usableHeight = height - (paddingY * 2);

  const x = paddingX + ((lng - minLng) / (maxLng - minLng)) * usableWidth;
  const y = height - (paddingY + ((lat - minLat) / (maxLat - minLat)) * usableHeight);

  return { x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
};

